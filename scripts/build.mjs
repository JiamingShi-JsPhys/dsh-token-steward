/**
 * 打包脚本。
 *
 * 产物形状与 @linxin666 全家桶一致，因为 DSH 的 client 加载器只认这一种：
 *  - `lib/index.js`  —— Host 半区，普通 ESM；
 *  - `lib/client.js`  —— Client 半区，必须是
 *    `window.__ModuleLoader__.load({ id, factory: (require) => … })` 的工厂形态，
 *    因为浏览器里没有 Node 的模块解析，react / react-dom 全由宿主注入。
 *
 * CSS 以 `<style data-plugin-css=…>` 注入，与 dsh-pet / dsh-usage 同一套约定：
 *  - 幂等（同一个 id 只会插一次），
 *  - 带 data-plugin 标记，卸载时可以按它清理。
 */
import { build } from 'esbuild'
import { readFile, writeFile, mkdir, rm, rename } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Windows 上两个构建进程并发写同一产物会得到 EPERM / Access denied
 * （对方句柄未关）。临时文件 + rename + 有界重试：每次重试仍是一次完整
 * 的原子替换，与 src/host/atomic-file.ts 的策略同源。
 */
async function writeFileAtomic(path, text) {
  const temporary = path + '.tmp-' + process.pid + '-' + String(Date.now())
  await writeFile(temporary, text)
  let delayMs = 25
  for (let attempt = 0; attempt < 8; attempt += 1) {
    try {
      await rename(temporary, path)
      return
    } catch (error) {
      if (attempt === 7) throw error
      await new Promise((resolve) => setTimeout(resolve, delayMs))
      delayMs *= 2
    }
  }
}

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const OUT = join(ROOT, 'lib')
const TMP = join(ROOT, '.cache')

/** 包名：既是 loader 的 id，也是 style 标签的 data-plugin。 */
const PKG = 'dsh-token-steward'

/**
 * 宿主在浏览器里注入的模块；打包时必须外置。
 * 打进一份自己的 React 会造成 hooks 双实例——那是界面上最难查的一类崩溃。
 */
const CLIENT_EXTERNAL = [
  'react',
  'react-dom',
  'react-dom/client',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-locale/client',
  '@deepseek-ai/dsh-client-ui-renderer/client',
  '@deepseek-ai/dsh-client-ui-slots',
]

/**
 * 把一份 CSS 包成「插入 style 标签」的前置代码。
 * @param css - 已压缩的样式文本。
 * @param id - 幂等标识（与全家桶同格式：包名 + 源文件）。
 */
function stylePrelude(css, id) {
  return [
    'const __stewardCss = ' + JSON.stringify(css) + ';',
    'const __stewardCssId = ' + JSON.stringify(id) + ';',
    'if (typeof document !== "undefined" && document.querySelector("style[data-plugin-css=" + JSON.stringify(__stewardCssId) + "]") === null) {',
    '  const tag = document.createElement("style");',
    '  tag.dataset.plugin = ' + JSON.stringify(PKG) + ';',
    '  tag.dataset.pluginCss = __stewardCssId;',
    '  tag.textContent = __stewardCss;',
    '  document.head.appendChild(tag);',
    '}',
  ].join('\n')
}

/** 打包 Client 半区，并包成 loader 工厂。 */
async function buildClient() {
  const result = await build({
    entryPoints: [join(ROOT, 'src/client/index.ts')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['es2022'],
    external: CLIENT_EXTERNAL,
    outfile: join(TMP, 'client.cjs'),
    logLevel: 'warning',
    legalComments: 'none',
  })
  if (result.errors.length > 0) throw new Error('client bundle failed')

  const js = await readFile(join(TMP, 'client.cjs'), 'utf8')
  const minified = await build({
    entryPoints: [join(TMP, 'client.cjs')],
    bundle: false,
    minify: true,
    // 压成一条几万字符的单行会让所有按行工作的工具失明：浏览器报错只给
    // 一个行号、静态扫描器会把整份 bundle 当成一个语句（`fetch` 与后面的
    // `secret` 相邻 → 误报数据外泄）。限一下行长，代价是几 KB。
    lineLimit: 200,
    format: 'cjs',
    write: false,
    logLevel: 'warning',
  })
  const body = minified.outputFiles === undefined ? js : (minified.outputFiles[0]?.text ?? js)

  // CSS 与 JS 是同一次打包的产物，因此类名映射与样式表天然一致。
  let css = ''
  try {
    css = await readFile(join(TMP, 'client.css'), 'utf8')
  } catch {
    throw new Error('client css was not emitted; is the module.css import still present?')
  }
  const cssMin = await build({
    stdin: { contents: css, loader: 'css', resolveDir: ROOT },
    minify: true,
    write: false,
    logLevel: 'warning',
  })
  const cssText = cssMin.outputFiles?.[0]?.text ?? css

  const wrapped = [
    'window.__ModuleLoader__.load({',
    '\tid: ' + JSON.stringify(PKG) + ',',
    '\tfactory: (require) => {',
    '\t\tvar module = { exports: {} };',
    '\t\tvar exports = module.exports;',
    stylePrelude(cssText, PKG + '/src/client/steward.module.css'),
    ...body.split('\n').map((line) => (line === '' ? '' : '\t\t' + line)),
    '\t\treturn module.exports;',
    '\t}',
    '});',
    '',
  ].join('\n')

  await writeFileAtomic(join(OUT, 'client.js'), wrapped)
  return { js: wrapped.length, css: cssText.length }
}

/** 打包 Host 半区（ESM）。 */
async function buildHost() {
  const result = await build({
    entryPoints: [join(ROOT, 'src/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    // yaml 由宿主提供（app.asar 里就有），打进包里只会多一份 200KB 的副本。
    external: ['yaml', 'js-yaml', 'node:*'],
    write: false,
    logLevel: 'warning',
    legalComments: 'none',
    banner: {
      js: '// dsh-token-steward · host half. Generated by scripts/build.mjs — do not edit.',
    },
  })
  if (result.errors.length > 0) throw new Error('host bundle failed')
  const text = result.outputFiles?.[0]?.text ?? ''
  if (text === '') throw new Error('host bundle produced no output')
  await writeFileAtomic(join(OUT, 'index.js'), text)
  return text.length
}

try {
  await rm(OUT, { recursive: true, force: true })
} catch {
  // 目录被并发构建者占用时不必清空：随后每次写都是原子替换。
}
await mkdir(OUT, { recursive: true })
await mkdir(TMP, { recursive: true })

const clientStats = await buildClient()
const hostSize = await buildHost()
console.log('lib/client.js', clientStats.js, 'bytes (css', clientStats.css + ')')
console.log('lib/index.js', hostSize, 'bytes')
